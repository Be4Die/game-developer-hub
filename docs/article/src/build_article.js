const pngSize = (f) => {
  const b = fs.readFileSync(f);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
};
const cm2px = (cm) => Math.round((cm / 2.54) * 96);

const run = (text, o = {}) => new TextRun({ text, font: FONT, size: o.size || 28, bold: o.bold, italics: o.italics });

// Основной абзац: по ширине, отступ 1,25 см, интервал 1,1
const para = (parts, o = {}) => new Paragraph({
  alignment: o.align || AlignmentType.JUSTIFIED,
  spacing: { line: 264, before: o.before || 0, after: o.after || 0 },
  indent: o.noIndent ? undefined : { firstLine: 709 },
  keepNext: o.keepNext,
  children: (Array.isArray(parts) ? parts : [parts]).map((p) => (typeof p === 'string' ? run(p, o) : p)),
});

const centered = (text, o = {}) => new Paragraph({
  alignment: AlignmentType.CENTER,
  spacing: { line: 264, before: o.before || 0, after: o.after || 0 },
  keepNext: o.keepNext,
  children: [run(text, o)],
});

const heading = (text) => new Paragraph({
  alignment: AlignmentType.LEFT,
  spacing: { line: 264, before: 160, after: 80 },
  keepNext: true,
  children: [run(text, { bold: true })],
});

// Абзац с жирным запевом («Обнаружение сервера. …»)
const lead = (title, text) => para([run(title + ' ', { bold: true }), run(text)]);

const figure = (file, widthCm, caption) => {
  const { w, h } = pngSize(path.join(ROOT, file));
  const wpx = cm2px(widthCm);
  const hpx = Math.round((wpx * h) / w);
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER, keepNext: true, spacing: { before: 120, after: 60 },
      children: [new ImageRun({ type: 'png', data: fs.readFileSync(path.join(ROOT, file)), transformation: { width: wpx, height: hpx } })],
    }),
    centered(caption, { size: 24, after: 160 }),
  ];
};

// Рисунок из двух частей: а) и б), каждая со своей подписью-буквой в общей подписи
const figure2 = (items, caption) => {
  const out = [];
  items.forEach(({ file, widthCm }) => {
    const { w, h } = pngSize(path.join(ROOT, file));
    const wpx = cm2px(widthCm);
    out.push(new Paragraph({
      alignment: AlignmentType.CENTER, keepNext: true, spacing: { before: 100, after: 40 },
      children: [new ImageRun({ type: 'png', data: fs.readFileSync(path.join(ROOT, file)), transformation: { width: wpx, height: Math.round((wpx * h) / w) } })],
    }));
    out.push(centered(items.length ? `${items.indexOf(items.find((x) => x.file === file)) === 0 ? 'а' : 'б'})` : '', { size: 24, keepNext: true }));
  });
  out.push(centered(caption, { size: 24, after: 160 }));
  return out;
};

const border = { style: BorderStyle.SINGLE, size: 4, color: '000000' };
const borders = { top: border, bottom: border, left: border, right: border };

